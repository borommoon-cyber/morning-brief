# 2) 야구 카드 (6번째 칸을 위/아래 반씩 나눠 표시)
# ---------------------------------------------------------------------
#   title : 반쪽 칸의 제목
#   query : 구글 뉴스 검색어
#   must  : 기사 제목에 반드시 있어야 하는 단어
#           (다른 팀 경기 기사에 팀 이름이 스쳐 지나가는 경우를 거르기 위함)
BASEBALL = [
    {
        "title": "두산 베어스",
        "query": '"두산 베어스"',
        "must": "두산",                                  # 제목에 반드시 있어야 하는 단어
        "must_any": ["승", "패"],                        # 이 중 하나 이상 있어야 함
        "must_digit": r"\d{1,2}\s*[-:대]\s*\d{1,2}",     # 점수(5-3, 5:3, 5대3)가 있어야 함
    },
    {
        "title": "한화 이글스",
        "query": '"한화 이글스"',
        "must": "한화",
        "must_any": ["승", "패"],
        "must_digit": r"\d{1,2}\s*[-:대]\s*\d{1,2}",
    },
]
